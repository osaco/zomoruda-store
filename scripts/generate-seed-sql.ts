/**
 * Generates supabase/seed.sql from the demo seed (single source of truth).
 * Run: npx tsx scripts/generate-seed-sql.ts
 */
import { createHash } from "node:crypto";
import { writeFileSync } from "node:fs";
import {
  seedBanners,
  seedCategories,
  seedCoupons,
  seedOccasions,
  seedProducts,
  seedSettings,
  seedZones,
} from "../src/lib/data/demo/seed";

const uuid = (key: string) => {
  const h = createHash("md5").update(key).digest("hex");
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-4${h.slice(13, 16)}-a${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const q = (v: unknown): string =>
  v === null || v === undefined ? "null" : typeof v === "number" || typeof v === "boolean" ? String(v) : `'${String(v).replace(/'/g, "''")}'`;

const lines: string[] = ["-- Generated by scripts/generate-seed-sql.ts — do not edit by hand", ""];

for (const c of seedCategories)
  lines.push(`insert into categories (id, name_ar, slug, description_ar, image_url, sort_order, is_active) values (${q(uuid(c.id))}, ${q(c.nameAr)}, ${q(c.slug)}, ${q(c.descriptionAr)}, ${q(c.imageUrl)}, ${c.sortOrder}, ${c.isActive});`);
for (const o of seedOccasions)
  lines.push(`insert into occasions (id, name_ar, slug, icon, sort_order, is_active) values (${q(uuid(o.id))}, ${q(o.nameAr)}, ${q(o.slug)}, ${q(o.icon)}, ${o.sortOrder}, ${o.isActive});`);
for (const z of seedZones)
  lines.push(`insert into delivery_zones (id, name_ar, fee, min_order, delivery_time_ar, sort_order, is_active) values (${q(uuid(z.id))}, ${q(z.nameAr)}, ${z.fee}, ${q(z.minOrder)}, ${q(z.deliveryTimeAr)}, ${z.sortOrder}, ${z.isActive});`);
for (const c of seedCoupons)
  lines.push(`insert into coupons (id, code, type, value, min_order, max_discount, usage_limit, is_active) values (${q(uuid(c.id))}, ${q(c.code)}, ${q(c.type)}, ${c.value}, ${q(c.minOrder)}, ${q(c.maxDiscount)}, ${q(c.usageLimit)}, ${c.isActive});`);
for (const b of seedBanners)
  lines.push(`insert into banners (id, title_ar, subtitle_ar, image_url, link_url, sort_order, is_active) values (${q(uuid(b.id))}, ${q(b.titleAr)}, ${q(b.subtitleAr)}, ${q(b.imageUrl)}, ${q(b.linkUrl)}, ${b.sortOrder}, ${b.isActive});`);
for (const s of seedSettings) lines.push(`insert into settings (key, value) values (${q(s.key)}, ${q(s.value)});`);

for (const p of seedProducts) {
  const id = uuid(p.id);
  lines.push("");
  lines.push(`insert into products (id, name_ar, slug, description_ar, price, compare_at_price, category_id, stock_qty, availability, is_featured, is_new, is_active, allow_name, allow_card_message, allow_photo_upload, sold_count) values (${q(id)}, ${q(p.nameAr)}, ${q(p.slug)}, ${q(p.descriptionAr)}, ${p.price}, ${q(p.compareAtPrice)}, ${q(uuid(p.categoryId))}, ${p.stockQty}, ${q(p.availability)}, ${p.isFeatured}, ${p.isNew}, ${p.isActive}, ${p.allowName}, ${p.allowCardMessage}, ${p.allowPhotoUpload}, ${p.soldCount});`);
  for (const i of p.images)
    lines.push(`insert into product_images (product_id, url, alt_ar, sort_order, is_primary) values (${q(id)}, ${q(i.url)}, ${q(i.altAr)}, ${i.sortOrder}, ${i.isPrimary});`);
  for (const o of p.occasionIds) lines.push(`insert into product_occasions (product_id, occasion_id) values (${q(id)}, ${q(uuid(o))});`);
  for (const o of p.options) {
    const values = JSON.stringify(o.values.map((v) => ({ value_ar: v.valueAr, price_delta: v.priceDelta })));
    lines.push(`insert into product_options (product_id, name_ar, values, is_required, sort_order) values (${q(id)}, ${q(o.nameAr)}, ${q(values)}::jsonb, ${o.isRequired}, ${o.sortOrder});`);
  }
}

writeFileSync("supabase/seed.sql", lines.join("\n") + "\n");
console.log("supabase/seed.sql written");
